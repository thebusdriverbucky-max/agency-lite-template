import { readFile, writeFile } from 'node:fs/promises';
import path from 'node:path';
import process from 'node:process';
import { fileURLToPath } from 'node:url';
import Ajv2020 from 'ajv/dist/2020.js';
import addFormats from 'ajv-formats';
import standaloneCode from 'ajv/dist/standalone/index.js';

const root = process.cwd();
const outputPath = path.join(root, 'lib/content-validators.generated.ts');
const schemaPaths = {
  config: 'content/schema/config.schema.json',
  work: 'content/schema/work.schema.json',
};

async function readJson(relativePath) {
  return JSON.parse(await readFile(path.join(root, relativePath), 'utf8'));
}

/**
 * Generate browser-safe validator functions from the checked-in schemas.
 *
 * Ajv is deliberately used only by this Node-side generation step. The
 * generated module contains validation code, not Ajv.compile/new Function,
 * so importing content-validation.ts in the browser never compiles a schema.
 */
export async function renderGeneratedValidators() {
  const [configSchema, workSchema] = await Promise.all([
    readJson(schemaPaths.config),
    readJson(schemaPaths.work),
  ]);

  const ajv = new Ajv2020({
    allErrors: true,
    strict: true,
    code: { esm: true, lines: true, source: true },
  });
  addFormats(ajv);
  ajv.addSchema(configSchema);
  ajv.addSchema(workSchema);

  let code = standaloneCode(ajv, {
    validateConfig: configSchema.$id,
    validateWork: workSchema.$id,
  });

  // Ajv's standalone output references two small runtime helpers with
  // CommonJS require(). Replace them with local static helpers so the client
  // bundle has no runtime module lookup or code evaluation path.
  code = code
    .replaceAll(
      'require("ajv/dist/runtime/ucs2length").default',
      'ucs2length',
    )
    .replaceAll(
      'require("ajv/dist/runtime/equal").default',
      'deepEqual',
    );

  if (code.includes('require(')) {
    throw new Error('Generated validators contain an unexpected require() call.');
  }

  return [
    '/* eslint-disable */',
    '// @ts-nocheck',
    '// Generated by scripts/generate-content-validators.mjs. Do not edit manually.',
    'function ucs2length(str) {',
    '  let length = 0;',
    '  for (let position = 0; position < str.length; position += 1) {',
    '    const value = str.charCodeAt(position);',
    '    if (value >= 0xd800 && value <= 0xdbff && position + 1 < str.length &&',
    '        (str.charCodeAt(position + 1) & 0xfc00) === 0xdc00) {',
    '      position += 1;',
    '    }',
    '    length += 1;',
    '  }',
    '  return length;',
    '}',
    'function deepEqual(a, b) {',
    '  if (a === b) return true;',
    '  if (a && b && typeof a === "object" && typeof b === "object") {',
    '    if (a.constructor !== b.constructor) return false;',
    '    if (Array.isArray(a)) {',
    '      if (a.length !== b.length) return false;',
    '      return a.every((value, index) => deepEqual(value, b[index]));',
    '    }',
    '    if (a.constructor === RegExp) return a.source === b.source && a.flags === b.flags;',
    '    if (a.valueOf !== Object.prototype.valueOf) return a.valueOf() === b.valueOf();',
    '    if (a.toString !== Object.prototype.toString) return a.toString() === b.toString();',
    '    const keys = Object.keys(a);',
    '    if (keys.length !== Object.keys(b).length) return false;',
    '    return keys.every((key) => Object.prototype.hasOwnProperty.call(b, key) && deepEqual(a[key], b[key]));',
    '  }',
    '  return Number.isNaN(a) && Number.isNaN(b);',
    '}',
    '',
    code.trim(),
    '',
  ].join('\n');
}

export async function checkGeneratedValidators() {
  const expected = await renderGeneratedValidators();
  let actual;

  try {
    actual = await readFile(outputPath, 'utf8');
  } catch {
    throw new Error(
      'Generated content validators are missing. Run npm run content:generate.',
    );
  }

  if (actual !== expected) {
    throw new Error(
      'Generated content validators are stale. Run npm run content:generate and review the result.',
    );
  }
}

async function main() {
  const generated = await renderGeneratedValidators();

  if (process.argv.includes('--check')) {
    await checkGeneratedValidators();
    console.log('Generated content validators are up to date.');
    return;
  }

  await writeFile(outputPath, generated, 'utf8');
  console.log(`Generated ${path.relative(root, outputPath)}.`);
}

const entrypoint = process.argv[1]
  ? path.resolve(process.argv[1])
  : null;

if (entrypoint === fileURLToPath(import.meta.url)) {
  await main();
}
